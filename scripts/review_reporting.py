def pm(values,decimals=2):
    v=pd.Series(values,dtype=float).dropna()
    if not len(v):return '--'
    return f'${v.mean():.{decimals}f}'+(rf'\pm{v.std():.{decimals}f}' if len(v)>1 else '')+'$'


