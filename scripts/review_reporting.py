def sustained_crossing(df,threshold,hold=50):
    """First logged loss crossing maintained at every log for at least hold steps."""
    good=(df.probe_loss<threshold).to_numpy();s=df.step.to_numpy()
    for i in np.flatnonzero(good):
        j=np.searchsorted(s,s[i]+hold)
        if j<len(s) and good[i:j+1].all():return float(s[i])
    return np.nan


def cluster_summary(df,draws=2000):
    """Percentile bootstrap of entire physical conditions, retaining their seeds/layers."""
    groups=[g[['p_model','p_meas']].dropna().to_numpy() for _,g in df.groupby(['exp','tag'])]
    def moments(a):
        x,y=a.T;return [len(a),x.sum(),y.sum(),(x*x).sum(),(y*y).sum(),(x*y).sum(),abs(x-y).sum()]
    m=np.array([moments(g) for g in groups]);rng=np.random.default_rng(190919)
    def calc(t):
        n,x,y,xx,yy,xy,ae=np.moveaxis(t,-1,0)
        return (n*xy-x*y)/np.sqrt(np.maximum((n*xx-x*x)*(n*yy-y*y),1e-30)),ae/n
    r,mae=calc(m.sum(0));boot=m[rng.integers(len(m),size=(draws,len(m)))].sum(1);rr,ee=calc(boot)
    return dict(n_conditions=len(m),n_points=sum(map(len,groups)),r=float(r),mae=float(mae),
                r_ci=np.quantile(rr,[.025,.975]).tolist(),mae_ci=np.quantile(ee,[.025,.975]).tolist())


